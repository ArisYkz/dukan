/** Build a CSSProperties object from a theme preset name and dark mode state */
export function getThemeStyleVars(preset: string, isDark: boolean = false): React.CSSProperties {
  const theme = STORE_THEMES[preset];
  if (!theme) return {};
  const vars = isDark ? theme.dark : theme.light;
  const style: Record<string, string> = {};
  for (const [key, value] of Object.entries(vars)) {
    style[key] = value;
  }
  return style as unknown as React.CSSProperties;
}
